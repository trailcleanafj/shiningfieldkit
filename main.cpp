#include <string>
#include <vector>

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

void balanced_sum() {
    int left = 1 + 2 + 3;
    int right = 4 + 2;
    bool balanced = (left == right);
    (void)balanced;
}

void integer_power() {
    int base = 2, exp = 8;
    int power = 1;
    for (int i = 0; i < exp; ++i) power *= base;
    (void)power;
}

extern "C" int gentle_beacon();
extern "C" void lunar_summit();
extern "C" void lucid_crescent();

int main() {
    count_vowels();
    collect_triples();
    balanced_sum();
    integer_power();
    lunar_summit();
    lucid_crescent();
    return gentle_beacon();
}
